""".claude/hooks/guard-github.sh 的测试：GitHub 工具不得发出带 AI 署名的内容。"""
import json
import subprocess
import unittest
from pathlib import Path

REPO = Path(__file__).resolve().parent.parent
HOOK = REPO / ".claude" / "hooks" / "guard-github.sh"


def run_hook(tool: str, tool_input: dict) -> str | None:
    """返回 permissionDecision（deny 等）；hook 放行时返回 None。"""
    payload = json.dumps({"tool_name": tool, "tool_input": tool_input})
    out = subprocess.run(
        ["bash", str(HOOK)], input=payload, capture_output=True, text=True,
        env={"PATH": "/usr/bin:/bin", "CLAUDE_PROJECT_DIR": str(REPO)}, check=True,
    ).stdout.strip()
    return json.loads(out)["hookSpecificOutput"]["permissionDecision"] if out else None


class GuardGithub(unittest.TestCase):
    def test_posting_tools_denied(self):
        for tool in ["create_pull_request", "issue_write", "add_issue_comment",
                     "add_reply_to_pull_request_comment", "pull_request_review_write"]:
            with self.subTest(tool=tool):
                self.assertEqual(run_hook(f"mcp__github__{tool}", {"body": "正文"}), "deny")

    def test_footer_in_update_denied(self):
        body = "正文\n\n---\n_Generated by [Claude Code](https://claude.ai/code/session_x)_"
        self.assertEqual(run_hook("mcp__github__update_pull_request", {"pullNumber": 1, "body": body}), "deny")

    def test_coauthor_in_nested_field_denied(self):
        files = [{"path": "a", "content": "Co-Authored-By: Claude <noreply@anthropic.com>"}]
        self.assertEqual(run_hook("mcp__github__update_pull_request", {"files": files}), "deny")

    def test_clean_update_allowed(self):
        self.assertIsNone(run_hook("mcp__github__update_pull_request", {"pullNumber": 1, "body": "改动前：……\n\n改动后：……"}))

    def test_read_tools_allowed(self):
        self.assertIsNone(run_hook("mcp__github__pull_request_read", {"method": "get", "pullNumber": 1}))


if __name__ == "__main__":
    unittest.main()
